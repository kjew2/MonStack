#!/usr/bin/env python3
"""Exports the picked creature art in tools/art/final/ to the web client (specs/26 section 8).

final/<key>.webp           portrait master (1024 px), key = species id or apex (chase tree) id
final/sprite/<key>.webp    battle sprite master, transparent background
-> web/art/portrait/<key>.webp (512 px) and web/art/sprite/<key>.webp (trimmed to the creature, 192 px)
-> web/art/keys.js, the keys that have both a portrait and a sprite (web/sprites.js draws generated art for exactly those).
   One key per line, sorted, so two lanes that each add a species merge cleanly; on a conflict, re-run this script.
Run after changing anything in final/. Needs Pillow (`--keys-only` rewrites keys.js from web/art/ without it).
"""
import glob, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
FINAL = os.path.join(HERE, "final")
WEB = os.path.join(os.path.dirname(os.path.dirname(HERE)), "web", "art")


def write_keys():
    """Writes web/art/keys.js: every key with both web/art/portrait/<key>.webp and web/art/sprite/<key>.webp."""
    def keys(d):
        return {os.path.basename(f)[:-5] for f in glob.glob(os.path.join(WEB, d, "*.webp"))}
    both = sorted(keys("portrait") & keys("sprite"))
    lines = ["// Generated by tools/art/export.py: the creature art keys web/art/ holds (specs/26 section 8). Do not edit by hand.",
             "self.MONSTACK_ART_KEYS = ["] + ['  "%s",' % k for k in both] + ["];"]
    with open(os.path.join(WEB, "keys.js"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    return both


def main():
    if "--keys-only" in sys.argv[1:]:
        print("wrote", len(write_keys()), "keys to", os.path.join(WEB, "keys.js"))
        return
    from PIL import Image
    os.makedirs(os.path.join(WEB, "portrait"), exist_ok=True)
    os.makedirs(os.path.join(WEB, "sprite"), exist_ok=True)
    for f in sorted(glob.glob(os.path.join(FINAL, "*.webp"))):
        key = os.path.basename(f)[:-5]
        Image.open(f).convert("RGB").resize((512, 512), Image.LANCZOS).save(
            os.path.join(WEB, "portrait", key + ".webp"), "WEBP", quality=80, method=6)
    for f in sorted(glob.glob(os.path.join(FINAL, "sprite", "*.webp"))):
        key = os.path.basename(f)[:-5]
        im = Image.open(f).convert("RGBA")
        box = im.getchannel("A").point(lambda a: 255 if a > 24 else 0).getbbox()   # trim faint halo pixels too
        im = im.crop(box)
        side = max(im.size)
        sq = Image.new("RGBA", (side, side), (0, 0, 0, 0))
        sq.paste(im, ((side - im.width) // 2, side - im.height))   # feet on the bottom edge
        sq.resize((192, 192), Image.LANCZOS).save(os.path.join(WEB, "sprite", key + ".webp"), "WEBP", quality=90, method=6)
    print("exported", len(glob.glob(os.path.join(WEB, "*", "*.webp"))), "files and", len(write_keys()), "keys to", WEB)


if __name__ == "__main__":
    main()
